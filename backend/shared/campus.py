def _distance_meters(lat1: float, lng1: float, lat2: float, lng2: float) -> float:
    """Haversine 直線距離（公尺），小範圍足夠精確。"""
    r = 6371000.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dlat = math.radians(lat2 - lat1)
    dlng = math.radians(lng2 - lng1)
    a = math.sin(dlat / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dlng / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


NOMINATIM_URL = "https://nominatim.openstreetmap.org/reverse"


async def resolve_road_name(latitude: float, longitude: float) -> str | None:
    """校外座標的路段名稱（Nominatim 逆向地理編碼）。

    純加值資訊：任何失敗（網路、限流、無路名資料）一律靜默回 None，
    呼叫端以「不顯示」處理即可。
    """
    try:
        async with httpx.AsyncClient(timeout=4.0) as client:
            response = await client.get(
                NOMINATIM_URL,
                params={
                    "format": "json",
                    "lat": latitude,
                    "lon": longitude,
                    "zoom": 17,
                    "addressdetails": 1,
                },
                headers={"User-Agent": "realtime-map-notice/1.0 (campus event map)"},
            )
            response.raise_for_status()
            return (response.json().get("address") or {}).get("road") or None
    except Exception as e:
        logger.warning("road name lookup failed: %s", e)
        return None


def resolve_campus_location(latitude: float, longitude: float) -> str | None:
    """座標在輔大範圍內時，回傳最近的地標名稱；校外或無匹配回 None。"""
    b = CAMPUS_BOUNDS
    if not (b["lat_min"] <= latitude <= b["lat_max"] and b["lng_min"] <= longitude <= b["lng_max"]):
        return None

    best: tuple[str, float] | None = None
    for name, poi_lat, poi_lng, radius in CAMPUS_POIS:
        dist = _distance_meters(latitude, longitude, poi_lat, poi_lng)
        if dist <= radius and (best is None or dist < best[1]):
            best = (name, dist)
    return best[0] if best else None
